USE master;
GO

IF EXISTS (SELECT name FROM sys.databases WHERE name = 'QuanLyQuanCafe')
    DROP DATABASE QuanLyQuanCafe;
GO

CREATE DATABASE QuanLyQuanCafe;
GO

USE QuanLyQuanCafe;
GO

-- 1. BẢNG CHI NHÁNH
CREATE TABLE CHINHANH (
    MaCN VARCHAR(20) PRIMARY KEY,
    TenCN NVARCHAR(100) NOT NULL,
    DiaChi NVARCHAR(255) NOT NULL,
    SDT VARCHAR(15),
    TrangThai VARCHAR(20) DEFAULT 'HoatDong'
);

-- 2. BẢNG NHÂN VIÊN
CREATE TABLE NHANVIEN (
    MaNV VARCHAR(20) PRIMARY KEY,
    TenNV NVARCHAR(100) NOT NULL,
    SDT VARCHAR(15),
    ChucVu NVARCHAR(50) NOT NULL,
    LuongTheoGio DECIMAL(18,2) DEFAULT 25000,
    TenDangNhap VARCHAR(50) UNIQUE NOT NULL,
    MatKhau VARCHAR(255) NOT NULL,
    MaCN VARCHAR(20) NOT NULL,
    CONSTRAINT FK_NhanVien_ChiNhanh FOREIGN KEY (MaCN) REFERENCES CHINHANH(MaCN)
);

-- 3. BẢNG CA LÀM
CREATE TABLE CALAM (
    MaCa VARCHAR(20) PRIMARY KEY,
    TenCa NVARCHAR(50) NOT NULL,
    GioBatDau TIME NOT NULL,
    GioKetThuc TIME NOT NULL
);

-- 4. BẢNG CHẤM CÔNG
CREATE TABLE CHAMCONG (
    MaChamCong BIGINT IDENTITY(1,1) PRIMARY KEY,
    MaNV VARCHAR(20) NOT NULL,
    MaCa VARCHAR(20) NOT NULL,
    NgayLam DATE NOT NULL,
    GioVao DATETIME NOT NULL,
    GioRa DATETIME NULL,
    SoGioThucTe FLOAT NULL,
    CONSTRAINT FK_ChamCong_NhanVien FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV),
    CONSTRAINT FK_ChamCong_CaLam FOREIGN KEY (MaCa) REFERENCES CALAM(MaCa)
);

-- 5. BẢNG LƯƠNG
CREATE TABLE BANGLUONG (
    MaBangLuong VARCHAR(30) PRIMARY KEY,
    MaNV VARCHAR(20) NOT NULL,
    Thang INT NOT NULL,
    Nam INT NOT NULL,
    TongGioLam FLOAT NOT NULL,
    LuongTheoGio DECIMAL(18,2) NOT NULL,
    PhuCap DECIMAL(18,2) DEFAULT 0,
    ThuongPhat DECIMAL(18,2) DEFAULT 0,
    ThucLinh DECIMAL(18,2) NOT NULL,
    CONSTRAINT FK_BangLuong_NhanVien FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
);

-- 6. BẢNG DANH MỤC
CREATE TABLE DANHMUC (
    MaDM VARCHAR(20) PRIMARY KEY,
    TenDM NVARCHAR(100) NOT NULL
);

-- 7. BẢNG MÓN CƠ SỞ
CREATE TABLE MON (
    MaMon VARCHAR(20) PRIMARY KEY,
    TenMon NVARCHAR(100) NOT NULL,
    MaDM VARCHAR(20) NOT NULL,
    HinhAnh VARCHAR(255) NULL,
    TrangThai VARCHAR(20) DEFAULT 'DangBan',
    CONSTRAINT FK_Mon_DanhMuc FOREIGN KEY (MaDM) REFERENCES DANHMUC(MaDM)
);

-- 8. BẢNG KÍCH CỠ (SIZE)
CREATE TABLE KICHCO (
    MaSize VARCHAR(10) PRIMARY KEY,
    TenSize NVARCHAR(20) NOT NULL
);

-- 9. BẢNG MÓN_SIZE (GIÁ BÁN THEO SIZE)
CREATE TABLE MON_SIZE (
    MaMonSize VARCHAR(30) PRIMARY KEY,
    MaMon VARCHAR(20) NOT NULL,
    MaSize VARCHAR(10) NOT NULL,
    GiaBan DECIMAL(18,2) NOT NULL,
    CONSTRAINT FK_MonSize_Mon FOREIGN KEY (MaMon) REFERENCES MON(MaMon),
    CONSTRAINT FK_MonSize_KichCo FOREIGN KEY (MaSize) REFERENCES KICHCO(MaSize)
);

-- 10. BẢNG NGUYÊN LIỆU
CREATE TABLE NGUYENLIEU (
    MaNL VARCHAR(20) PRIMARY KEY,
    TenNL NVARCHAR(100) NOT NULL,
    DonViTinh NVARCHAR(20) NOT NULL,
    NguongBao FLOAT DEFAULT 10
);

-- 11. BẢNG CÔNG THỨC ĐỊNH LƯỢNG (BOM)
CREATE TABLE CONGTHUC (
    MaMonSize VARCHAR(30) NOT NULL,
    MaNL VARCHAR(20) NOT NULL,
    SoLuongTieuHao FLOAT NOT NULL,
    PRIMARY KEY (MaMonSize, MaNL),
    CONSTRAINT FK_CongThuc_MonSize FOREIGN KEY (MaMonSize) REFERENCES MON_SIZE(MaMonSize),
    CONSTRAINT FK_CongThuc_NguyenLieu FOREIGN KEY (MaNL) REFERENCES NGUYENLIEU(MaNL)
);

-- 12. BẢNG BÀN
CREATE TABLE BAN (
    MaBan VARCHAR(30) PRIMARY KEY,
    SoBan NVARCHAR(20) NOT NULL,
    KhuVuc NVARCHAR(50),
    MaCN VARCHAR(20) NOT NULL,
    TrangThai VARCHAR(20) DEFAULT 'Trong',
    CONSTRAINT FK_Ban_ChiNhanh FOREIGN KEY (MaCN) REFERENCES CHINHANH(MaCN)
);

-- 13. BẢNG KHÁCH HÀNG
CREATE TABLE KHACHHANG (
    MaKH VARCHAR(20) PRIMARY KEY,
    TenKH NVARCHAR(100) NOT NULL,
    SDT VARCHAR(15) UNIQUE NOT NULL,
    DiemTichLuy INT DEFAULT 0
);

-- 14. BẢNG HÓA ĐƠN
CREATE TABLE HOADON (
    MaHD VARCHAR(30) PRIMARY KEY,
    MaCN VARCHAR(20) NOT NULL,
    MaBan VARCHAR(30) NULL,
    MaNV VARCHAR(20) NOT NULL,
    MaKH VARCHAR(20) NULL,
    NgayLap DATETIME NOT NULL DEFAULT GETDATE(),
    TongTien DECIMAL(18,2) NOT NULL,
    GiamGia DECIMAL(18,2) DEFAULT 0,
    TongThanhToan DECIMAL(18,2) NOT NULL,
    HinhThucTT VARCHAR(30) NOT NULL,
    TrangThai VARCHAR(20) DEFAULT 'HoanThanh',
    CONSTRAINT FK_HoaDon_ChiNhanh FOREIGN KEY (MaCN) REFERENCES CHINHANH(MaCN),
    CONSTRAINT FK_HoaDon_Ban FOREIGN KEY (MaBan) REFERENCES BAN(MaBan),
    CONSTRAINT FK_HoaDon_NhanVien FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV),
    CONSTRAINT FK_HoaDon_KhachHang FOREIGN KEY (MaKH) REFERENCES KHACHHANG(MaKH)
);

-- 15. BẢNG CHI TIẾT HÓA ĐƠN
CREATE TABLE CHITIETHOADON (
    MaCTHD BIGINT IDENTITY(1,1) PRIMARY KEY,
    MaHD VARCHAR(30) NOT NULL,
    MaMonSize VARCHAR(30) NOT NULL,
    SoLuong INT NOT NULL CHECK (SoLuong > 0),
    DonGia DECIMAL(18,2) NOT NULL,
    ThanhTien DECIMAL(18,2) NOT NULL,
    CONSTRAINT FK_CTHD_HoaDon FOREIGN KEY (MaHD) REFERENCES HOADON(MaHD),
    CONSTRAINT FK_CTHD_MonSize FOREIGN KEY (MaMonSize) REFERENCES MON_SIZE(MaMonSize)
);

-- 16. BẢNG TỒN KHO CHI NHÁNH
CREATE TABLE TONKHO (
    MaCN VARCHAR(20) NOT NULL,
    MaNL VARCHAR(20) NOT NULL,
    SoLuongTon FLOAT NOT NULL DEFAULT 0,
    PRIMARY KEY (MaCN, MaNL),
    CONSTRAINT FK_TonKho_ChiNhanh FOREIGN KEY (MaCN) REFERENCES CHINHANH(MaCN),
    CONSTRAINT FK_TonKho_NguyenLieu FOREIGN KEY (MaNL) REFERENCES NGUYENLIEU(MaNL)
);

-- 17. BẢNG NHÀ CUNG CẤP
CREATE TABLE NHACUNGCAP (
    MaNCC VARCHAR(20) PRIMARY KEY,
    TenNCC NVARCHAR(150) NOT NULL,
    SDT VARCHAR(15)
);

-- 18. BẢNG PHIẾU KHO ĐA NĂNG
CREATE TABLE PHIEUKHO (
    MaPhieu VARCHAR(30) PRIMARY KEY,
    LoaiPhieu VARCHAR(20) NOT NULL, -- 'NHAP', 'XUAT_HUY', 'CHUYEN_KHO'
    MaCN VARCHAR(20) NOT NULL,
    MaNCC VARCHAR(20) NULL,
    MaNV VARCHAR(20) NOT NULL,
    NgayLap DATETIME NOT NULL DEFAULT GETDATE(),
    TongTien DECIMAL(18,2) NULL,
    CONSTRAINT FK_PhieuKho_ChiNhanh FOREIGN KEY (MaCN) REFERENCES CHINHANH(MaCN),
    CONSTRAINT FK_PhieuKho_NCC FOREIGN KEY (MaNCC) REFERENCES NHACUNGCAP(MaNCC),
    CONSTRAINT FK_PhieuKho_NhanVien FOREIGN KEY (MaNV) REFERENCES NHANVIEN(MaNV)
);

-- 19. BẢNG CHI TIẾT PHIẾU KHO
CREATE TABLE CHITIETPHIEUKHO (
    MaPhieu VARCHAR(30) NOT NULL,
    MaNL VARCHAR(20) NOT NULL,
    SoLuong FLOAT NOT NULL CHECK (SoLuong > 0),
    DonGia DECIMAL(18,2) NULL,
    PRIMARY KEY (MaPhieu, MaNL),
    CONSTRAINT FK_CTPK_PhieuKho FOREIGN KEY (MaPhieu) REFERENCES PHIEUKHO(MaPhieu),
    CONSTRAINT FK_CTPK_NguyenLieu FOREIGN KEY (MaNL) REFERENCES NGUYENLIEU(MaNL)
);
GO

